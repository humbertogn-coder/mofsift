"""Reference pages generated from the code, so that they cannot drift from it.

``docs/config.md`` lists every key of the config file (from the pydantic models) and
``docs/columns.md`` every column a stage writes (from :mod:`mofsift.columns`). Write them
again after changing a model or a column::

    python -m mofsift.docgen docs

A test compares the files with what this module produces.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

from pydantic import BaseModel
from pydantic_core import PydanticUndefined

from mofsift import runner  # noqa: F401  (importing the stages registers the types of their columns)
from mofsift.columns import COLUMN_INFO, ID_DESCRIPTION, JSON_TYPES
from mofsift.config import Config
from mofsift.io.tables import column_types

GENERATED_NOTE = (
    "<!-- Generated by `python -m mofsift.docgen docs`. Do not edit by hand; "
    "change the code and run the command again. -->"
)

CONFIG_PAGE = "config.md"
COLUMNS_PAGE = "columns.md"

_TYPE_WORDS = {str: "text", int: "whole number", float: "number", bool: "true / false", Path: "path"}

# Titles of the groups of columns, in the order of the pipeline.
_GROUP_TITLES = {
    "generate": ("generate", "generate-and-qc.md"),
    "qc": ("qc", "generate-and-qc.md"),
    "describe.composition": ("describe: composition", "describe.md"),
    "describe.geometry": ("describe: pore geometry (Zeo++)", "describe.md"),
    "describe.xtb": ("describe: xTB", "describe.md"),
    "score": ("score", "score.md"),
    "filter": ("filter", "export.md"),
}


def _model_in(annotation: Any) -> type[BaseModel] | None:
    """The pydantic model an annotation holds, also inside ``Model | None``."""
    for candidate in (annotation, *get_args(annotation)):
        if isinstance(candidate, type) and issubclass(candidate, BaseModel):
            return candidate
    return None


def _literal(value: Any) -> str:
    """A value the way it is written in a YAML config."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, Path):
        return value.as_posix()
    if isinstance(value, (list, dict)):
        return json.dumps(value).replace('"', "")
    return str(value)


def _type_text(annotation: Any) -> str:
    """A reader's description of what a key accepts."""
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Literal:
        return " \\| ".join(f"`{_literal(a)}`" for a in args)
    if origin is list:
        return f"list of {_type_text(args[0])}" if args else "list"
    if origin is dict:
        return f"mapping of {_type_text(args[0])} to {_type_text(args[1])}"
    if origin is Union or type(annotation).__name__ == "UnionType":
        parts = [_type_text(a) for a in args if a is not type(None)]
        if type(None) in args:
            parts.append("`null`")
        return " \\| ".join(dict.fromkeys(parts))
    return _TYPE_WORDS.get(annotation, getattr(annotation, "__name__", str(annotation)))


def _default_text(field: Any) -> str:
    if field.is_required():
        return "**required**"
    value = field.default
    if value is PydanticUndefined:
        value = field.default_factory()
    if isinstance(value, BaseModel):
        return ""
    if isinstance(value, list) and len(value) > 3:
        return "all of them" if all(isinstance(v, str) for v in value) else f"`{_literal(value)}`"
    return f"`{_literal(value)}`"


def _bounds(field: Any) -> str:
    """Limits declared on a numeric key, e.g. '> 0, <= 1.5'."""
    words = {"gt": ">", "ge": ">=", "lt": "<", "le": "<="}
    found = [
        f"{words[k]} {getattr(m, k):g}"
        for m in field.metadata
        for k in words
        if getattr(m, k, None) is not None
    ]
    return ", ".join(found)


def _doc(model: type[BaseModel]) -> str:
    return " ".join((model.__doc__ or "").split())


def _cell(text: str) -> str:
    """Text made safe for a cell of a Markdown table (no stray HTML tag, pipe or emphasis)."""
    return (
        " ".join(text.split())
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("|", "\\|")
        .replace("*", "\\*")
    )


def _section(model: type[BaseModel], path: str, lines: list[str], optional: bool = False) -> None:
    """One table for the leaf keys of ``model``, then one section per nested model."""
    leaves = [(n, f) for n, f in model.model_fields.items() if _model_in(f.annotation) is None]
    nested = [(n, f) for n, f in model.model_fields.items() if _model_in(f.annotation) is not None]
    if path:
        lines += [f"## `{path}`", ""]
        if _doc(model):
            lines += [_cell(_doc(model)), ""]
        if optional:
            lines += ["Optional: leave the section out when you do not need it.", ""]
    if leaves:
        lines += ["| Key | Accepts | Default | Meaning |", "|---|---|---|---|"]
        for name, field in leaves:
            meaning = _cell(field.description or "")
            bounds = _bounds(field)
            accepts = _type_text(field.annotation) + (f" ({bounds})" if bounds else "")
            key = f"{path}.{name}" if path else name
            lines.append(f"| `{key}` | {accepts} | {_default_text(field)} | {meaning} |")
        lines.append("")
    for name, field in nested:
        sub = _model_in(field.annotation)
        optional = type(None) in get_args(field.annotation)
        _section(sub, f"{path}.{name}" if path else name, lines, optional)


def undocumented_config_keys(model: type[BaseModel] = Config, path: str = "") -> list[str]:
    """Leaf keys of the config that have no description (a test keeps this list empty)."""
    missing: list[str] = []
    for name, field in model.model_fields.items():
        key = f"{path}.{name}" if path else name
        sub = _model_in(field.annotation)
        if sub is not None:
            if not _doc(sub):
                missing.append(key)
            missing += undocumented_config_keys(sub, key)
        elif not (field.description or "").strip():
            missing.append(key)
    return missing


def config_reference_markdown() -> str:
    """The page ``docs/config.md``."""
    lines = [
        GENERATED_NOTE,
        "",
        "# Config reference",
        "",
        "Every key of the config file, with what it accepts and its default. `mofsift init` writes",
        "a commented config with the same keys, which is the easier place to start; the guides of",
        "the stages explain what the settings do ([index](README.md)).",
        "",
        "- A key that is not listed here is an error, with a suggestion when it looks like a typo.",
        "- Paths are relative to the folder that holds the config file.",
        "- `mofsift doctor config.yaml` validates a config and shows what would run, without",
        "  computing anything.",
        "- The same reference as a JSON Schema, for editors that can use one:",
        "  `src/mofsift/schemas/config.schema.json`.",
        "",
        "## Top level",
        "",
    ]
    _section(Config, "", lines)
    return "\n".join(lines).rstrip("\n") + "\n"


def columns_reference_markdown() -> str:
    """The page ``docs/columns.md``."""
    lines = [
        GENERATED_NOTE,
        "",
        "# Column reference",
        "",
        "Every column mofsift writes, grouped by the stage that writes it. The same dictionary",
        "travels with every bundle, in the `columns` section of its `manifest.json`.",
        "",
        "- An empty cell (CSV) or `null` (JSON) means the value was not computed. It never means",
        "  zero.",
        "- Each stage also writes `<stage>_status` (`ok`, `skipped` or `failed`) and",
        "  `<stage>_skip_reason`.",
        "- Columns of your own table are kept and exported; they are not listed here.",
        "",
    ]
    types = column_types()
    groups: dict[str, list[str]] = {}
    for name, info in COLUMN_INFO.items():
        groups.setdefault(info.group, []).append(name)
    for group, (title, guide) in _GROUP_TITLES.items():
        names = groups.pop(group, [])
        if not names:
            continue
        lines += [f"## {title}", "", f"Guide: [{guide}]({guide}).", ""]
        lines += ["| Column | Type | Unit | Meaning |", "|---|---|---|---|"]
        if group == "generate":
            lines.append(f"| `id` | string | | {_cell(ID_DESCRIPTION)} |")
        for name in names:
            info = COLUMN_INFO[name]
            kind = JSON_TYPES[types[name]]
            lines.append(f"| `{name}` | {kind} | {info.unit or ''} | {_cell(info.description)} |")
        lines.append("")
    if groups:  # a new group must be given a title above before it can be documented
        raise ValueError(f"columns in groups without a title: {sorted(groups)}")
    return "\n".join(lines).rstrip("\n") + "\n"


PAGES = {CONFIG_PAGE: config_reference_markdown, COLUMNS_PAGE: columns_reference_markdown}


def write_pages(folder: str | Path) -> list[Path]:
    """Write the generated pages into ``folder`` (LF line endings) and return their paths."""
    folder = Path(folder)
    written = []
    for name, build in PAGES.items():
        path = folder / name
        path.write_text(build(), encoding="utf-8", newline="\n")
        written.append(path)
    return written


if __name__ == "__main__":  # pragma: no cover
    if len(sys.argv) != 2:
        sys.exit("usage: python -m mofsift.docgen DOCS_FOLDER")
    for written_path in write_pages(sys.argv[1]):
        print(written_path)
